"""Finish the separate security runtime; never alter a released converter."""
from pathlib import Path
import hashlib
import importlib.metadata as metadata
import json
import shutil
import sys
from PyInstaller.archive.readers import CArchiveReader, ZlibArchiveReader

root = Path(__file__).resolve().parents[1]
built = root / 'converter/runtime-v010-security-build/Formnaro-Konverter'
target = root / 'converter/runtime-v010-security'
proof_dir = root / 'work/security-0104'
expected = {'pillow': '13.0.0', 'setuptools': '84.2.1'}
for name, version in expected.items():
    if metadata.version(name) != version:
        raise RuntimeError('Unexpected build dependency: '+name)
if target.exists():
    raise RuntimeError('Separate runtime already exists; preserve it and choose a new build directory')
pins = json.loads((root/'converter/provenance.json').read_text())
sha = lambda p: hashlib.file_digest(p.open('rb'), 'sha256').hexdigest()
configuration_changes = []
for source in pins['engineSourceFiles']:
    current = sha(root/'converter'/source['file'])
    if current != source['sha256']:
        if source['file'] not in {'pyproject.toml', 'uv.lock'}:
            raise RuntimeError('Original engine source changed: '+source['file'])
        configuration_changes.append({'file': source['file'], 'previousSha256': source['sha256'], 'sha256': current})
        source['sha256'] = current

shutil.copytree(built, target)
shutil.copytree(root/'converter/examples', target/'examples')
shutil.copytree(root/'converter/runtime-v010/Lizenzen', target/'Lizenzen',
                ignore=shutil.ignore_patterns('pillow', 'setuptools'))
for name in expected:
    dist = metadata.distribution(name)
    info = Path(dist._path)
    # Include actual wheel metadata and all upstream license texts, not local
    # environment/cache bookkeeping generated by the installer.
    for destination in [target/'_internal'/info.name, target/'Lizenzen'/name/info.name]:
        destination.mkdir(parents=True)
        for item in info.iterdir():
            if item.name in {'METADATA', 'WHEEL', 'RECORD', 'entry_points.txt', 'top_level.txt'} or item.name.lower().startswith(('license', 'copying', 'notice')):
                if item.is_dir():
                    shutil.copytree(item, destination/item.name)
                else:
                    shutil.copy2(item, destination/item.name)
    if name == 'setuptools':
        vendor = Path(dist.locate_file('setuptools/_vendor'))
        for item in vendor.rglob('*'):
            if item.is_file() and (item.name.lower().startswith(('license', 'copying', 'notice')) or item.name == 'METADATA'):
                destination = target/'Lizenzen/setuptools/vendor'/item.relative_to(vendor)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(item, destination)

archive = CArchiveReader(str(target/'Formnaro-Konverter.exe'))
pyz = proof_dir/'native-security-PYZ.pyz'
pyz.write_bytes(archive.extract('PYZ.pyz'))
modules = ZlibArchiveReader(str(pyz))
if '13.0.0' not in modules.extract('PIL._version').co_consts:
    raise RuntimeError('Frozen executable does not contain Pillow 13')
import PIL
original_binary = Path(PIL.__file__).parent/'_imaging.cp313-win_amd64.pyd'
frozen_binary = target/'_internal/PIL'/original_binary.name
if sha(original_binary) != sha(frozen_binary):
    raise RuntimeError('Frozen imaging binary differs from the installed patched wheel')

previous = {k: pins[k] for k in ['headlessExeSha256', 'origin']}
pins.update(runtimeDirectory='runtime-v010-security',
    headlessExeSha256=sha(target/'Formnaro-Konverter.exe'),
    runtimeSecurity={'previousBuild': previous, 'python': sys.version.split()[0],
        'pyinstaller': metadata.version('pyinstaller'), 'dependencies': expected,
        'imagingBinarySha256': sha(frozen_binary),
        'configurationChanges': configuration_changes,
        'scope': 'Dependency rebuild; engine Python modules and bridge unchanged. Only dependency configuration pins changed. Separate runtime and dependency metadata/licenses retained.'})
(root/'converter/provenance.json').write_text(json.dumps(pins, indent=2)+'\n')
inventory = [{'file': p.relative_to(target).as_posix(), 'sha256': sha(p)}
             for p in sorted(target.rglob('*')) if p.is_file()]
(proof_dir/'native-runtime.json').write_text(json.dumps({'runtime': str(target), 'files': inventory, 'versions': expected}, indent=2))
print(json.dumps({'ok': True, 'runtime': str(target), 'files': len(inventory), 'dependencies': expected}))
